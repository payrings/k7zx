void LoaderRoutine::load(const std::uint8_t* src, std::size_t n) {
    std::memset(buf_, 0, sizeof(buf_));
    if (n > kCapacity) n = kCapacity;
    std::memcpy(buf_, src, n);
}

std::size_t LoaderRoutine::bodyLength() const {
    // The original used `strlen(loaderRoutine + 5)`; the blobs are NUL terminated.
    std::size_t n = 0;
    while (5 + n < kCapacity && buf_[5 + n] != 0) ++n;
    return n;
}

